@dataclass
class InventoryState:
    """Mutable per-item inventory tracker updated each planning cycle.

    Attributes:
        on_hand: Current physical on-hand quantity.
        allocated: Quantity already committed to open orders.
        safety_stock: Minimum target buffer stock.
        lead_time: Replenishment lead time in periods.
        lot_sizing_rule: Lot-sizing rule (LFL, EOQ, FPQ …).
        scheduled_receipts: Dict[period → quantity] of firm inbound orders.
    """
    on_hand: float
    allocated: float = 0.0
    safety_stock: float = 0.0
    lead_time: int = 1
    lot_sizing_rule: str = "LFL"
    scheduled_receipts: Dict[int, float] = field(default_factory=dict)

    # --- Demand history (used by nervousness / safety-stock algorithms) ---
    demand_history: List[float] = field(default_factory=list)

    def available_balance(self) -> float:
        """Projected Available Balance = on_hand - allocated."""
        return max(0.0, self.on_hand - self.allocated)

    def apply_receipt(self, period: int, quantity: float) -> None:
        """Record an incoming receipt for a future period."""
        self.scheduled_receipts[period] = self.scheduled_receipts.get(period, 0.0) + quantity

    def apply_issue(self, quantity: float) -> None:
        """Deduct consumed quantity from on-hand stock (floor at 0)."""
        self.on_hand = max(0.0, self.on_hand - quantity)

    def apply_adjustment(self, delta: float) -> None:
        """Apply a physical inventory count adjustment (positive or negative)."""
        self.on_hand = max(0.0, self.on_hand + delta)

    def to_mrp_dict(self) -> Dict[str, Any]:
        """Return dict compatible with BOMExplosionEngine / NettingEngine."""
        return {
            "on_hand": self.on_hand,
            "allocated": self.allocated,
            "safety_stock": self.safety_stock,
            "lead_time": self.lead_time,
            "lot_sizing_rule": self.lot_sizing_rule,
        }


@dataclass
class CycleAuditRecord:
    """Immutable log of a single closed-loop planning cycle.

    Attributes:
        cycle: Planning cycle index (1-based).
        planning_period: The period t for which this cycle ran.
        timestamp: ISO-8601 wall-clock time of the cycle.
        forecast_status: Status string from ForecastApiClient ('SUCCESS', 'FALLBACK_*').
        num_planned_orders: Total planned orders generated by MRP.
        num_released_orders: Orders released for period t+1.
        num_capacity_exceptions: Capacity violations detected.
        is_capacity_feasible: Whether the final plan is capacity-feasible.
        nervousness_index: Composite plan-change index vs. previous cycle.
        fill_rate: Actual vs. planned fill rate from DES actuals (None if no actuals yet).
        des_export_path: Filepath of DES export written this cycle.
        notes: Optional free-text annotations.
    """
    cycle: int
    planning_period: int
    timestamp: str
    forecast_status: str
    num_planned_orders: int
    num_released_orders: int
    num_capacity_exceptions: int
    is_capacity_feasible: bool
    nervousness_index: float
    fill_rate: Optional[float]
    des_export_path: Optional[str]
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SimulationSummary:
    """Aggregate report produced after a multi-period closed-loop simulation.

    Attributes:
        num_periods: Total planning periods simulated.
        total_planned_orders: Cumulative planned orders across all cycles.
        total_released_orders: Cumulative orders released to the floor.
        avg_nervousness_index: Mean plan-nervousness across all cycles.
        max_nervousness_index: Peak nervousness observed.
        avg_fill_rate: Mean fill rate (from DES actuals) across cycles with actuals.
        total_capacity_exceptions: Cumulative capacity violations.
        service_level_pct: Pct of cycles where fill_rate >= target_fill_rate.
        nervousness_trend: List of per-cycle nervousness_index values.
        cycle_audit_records: Full list of :class:`CycleAuditRecord` objects.
    """
    num_periods: int
    total_planned_orders: int
    total_released_orders: int
    avg_nervousness_index: float
    max_nervousness_index: float
    avg_fill_rate: float
    total_capacity_exceptions: int
    service_level_pct: float
    nervousness_trend: List[float]
    cycle_audit_records: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


