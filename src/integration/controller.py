# Closed-Loop Planning Controller
# ---------------------------------------------------------------------------


class ClosedLoopPlanningController:
    """Orchestrates rolling-horizon MRP with feedback from DES execution.

    The controller ties together:
    - ``ForecastApiClient``          → demand sensing
    - ``BOMExplosionEngine``         → multi-level MRP
    - ``PlanComparator``             → frozen-window time-fence enforcement
    - ``CapacityAwareMRPPipeline``   → RCCP + leveling
    - ``DESExporter``                → planned order handoff to DES
    - ``NervousnessAnalyzer``        → stability tracking

    Parameters
    ----------
    item_ids:
        Finished-good item IDs to plan.
    inventory_states:
        Initial inventory state per item id.
    explosion_engine:
        Configured multi-level BOM explosion engine.
    rccp_engine:
        Configured RCCP engine (can be None → capacity check skipped).
    forecast_client:
        ``ForecastApiClient`` instance (optional; uses default synthetic).
    planning_horizon:
        Number of periods in the rolling horizon window (default 12).
    frozen_periods:
        Frozen window length in periods (default 2).
    slushy_periods:
        Slushy window length in periods (default 3).
    allow_slushy_changes:
        Whether slushy-zone changes are auto-approved (default False).
    des_export_dir:
        Directory for DES export files (default 'data/des_exports').
    target_fill_rate:
        Target fill rate for service-level calculation (default 0.95).
    """

    def __init__(
        self,
        item_ids: List[str],
        inventory_states: Dict[str, InventoryState],
        explosion_engine: BOMExplosionEngine,
        rccp_engine: Optional[RCCPEngine] = None,
        forecast_client: Optional[ForecastApiClient] = None,
        planning_horizon: int = 12,
        frozen_periods: int = 2,
        slushy_periods: int = 3,
        allow_slushy_changes: bool = False,
        des_export_dir: str = "data/des_exports",
        target_fill_rate: float = 0.95,
    ) -> None:
        self.item_ids = list(item_ids)
        self.inventory_states: Dict[str, InventoryState] = inventory_states
        self.explosion_engine = explosion_engine
        self.rccp_engine = rccp_engine
        self.forecast_client = forecast_client or ForecastApiClient()
        self.planning_horizon = planning_horizon
        self.frozen_periods = frozen_periods
        self.slushy_periods = slushy_periods
        self.allow_slushy_changes = allow_slushy_changes
        self.des_export_dir = des_export_dir
        self.target_fill_rate = target_fill_rate

        # Internal state
        self._current_period: int = 0
        self._previous_plan: List[Dict[str, Any]] = []
        self._order_history: List[PlannedOrderExport] = []
        self._execution_history: List[ExecutionRecord] = []
        self._audit_trail: List[CycleAuditRecord] = []
        self._nervousness_history: List[NervousnessMetrics] = []

        # Sub-components
        _policy = TimeFencePolicy(
            frozen_periods=frozen_periods,
            slushy_periods=slushy_periods,
        )
        self._plan_comparator = PlanComparator(policy=_policy)
        self._nervousness_analyzer = NervousnessAnalyzer()

        # Capacity pipeline (optional)
        self._capacity_pipeline: Optional[CapacityAwareMRPPipeline] = None
        if rccp_engine is not None:
            self._capacity_pipeline = CapacityAwareMRPPipeline(
                explosion_engine=explosion_engine,
                rccp_engine=rccp_engine,
            )

        os.makedirs(des_export_dir, exist_ok=True)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    @property
    def current_period(self) -> int:
        """Current planning period."""
        return self._current_period

    @property
    def audit_trail(self) -> List[CycleAuditRecord]:
        """Read-only audit trail of all completed cycles."""
        return list(self._audit_trail)

    @property
    def nervousness_history(self) -> List[NervousnessMetrics]:
        """Read-only nervousness metrics history."""
        return list(self._nervousness_history)

    def run_planning_cycle(
        self,
        t: int,
        execution_results: Optional[List[ExecutionRecord]] = None,
        demand_actuals: Optional[Dict[str, float]] = None,
        inventory_adjustments: Optional[Dict[str, float]] = None,
    ) -> CycleAuditRecord:
        """Execute one complete closed-loop planning cycle for period t.

        Steps (from Phase 6.3 spec):
          1. Observe actual demand and execution results up to t.
          2. Fetch updated forecast for t+1 to t+H (no future leakage).
          3. Update inventory state (receipts, issues, adjustments).
          4. Run MRP with frozen window enforcement.
          5. Run capacity check and leveling.
          6. Release orders for period t+1 (within fence).
          7. Export to DES for execution.
          8. Record plan vs. actual for nervousness calculation.

        Parameters
        ----------
        t:
            Current planning period (1-based).
        execution_results:
            DES/shop-floor actuals received for orders due up to t.
        demand_actuals:
            Dict[item_id → actual_demand] consumed in period t.
        inventory_adjustments:
            Dict[item_id → delta] for physical count adjustments.

        Returns
        -------
        CycleAuditRecord with all cycle metrics.
        """
        self._current_period = t
        cycle_num = len(self._audit_trail) + 1
        timestamp = datetime.datetime.now().isoformat()
        notes_parts: List[str] = []

        logger.info(f"[Cycle {cycle_num}] Planning for period t={t}")

        # ---- Step 1: Observe actual demand and execution results --------
        if execution_results:
            self._execution_history.extend(execution_results)
        if demand_actuals:
            for item_id, consumed in demand_actuals.items():
                if item_id in self.inventory_states:
                    self.inventory_states[item_id].apply_issue(consumed)
                    self.inventory_states[item_id].demand_history.append(consumed)

        # ---- Step 2: Fetch updated forecast for t+1 → t+H -------------
        # Strict: start_period = t + 1 → no current/past period in forecast
        forecast_start = t + 1
        forecast: ForecastResponse = self.forecast_client.fetch_rolling_forecast(
            item_ids=self.item_ids,
            start_period=forecast_start,
            horizon_length=self.planning_horizon,
            force_refresh=True,
        )
        gross_requirements: Dict[str, List[float]] = forecast.to_mrp_gross_requirements()
        notes_parts.append(f"forecast_status={forecast.status}")

        # ---- Step 3: Update inventory state ----------------------------
        # Apply scheduled receipts that fall in period t (arrived this period)
        for item_id, inv in self.inventory_states.items():
            receipt_qty = inv.scheduled_receipts.pop(t, 0.0)
            if receipt_qty > 0:
                inv.on_hand += receipt_qty
        # Apply explicit adjustments
        if inventory_adjustments:
            for item_id, delta in inventory_adjustments.items():
                if item_id in self.inventory_states:
                    self.inventory_states[item_id].apply_adjustment(delta)

        # ---- Step 4: Run MRP with frozen window enforcement -----------
        inventory_status = {
            iid: inv.to_mrp_dict()
            for iid, inv in self.inventory_states.items()
        }
        scheduled_receipts_map: Dict[str, Dict[int, float]] = {
            iid: dict(inv.scheduled_receipts)
            for iid, inv in self.inventory_states.items()
        }

        periods = list(range(forecast_start, forecast_start + self.planning_horizon))

        # Convert scheduled_receipts mapping (Dict[int, float]) to ordered List[float] matching periods
        scheduled_receipts_by_period: Dict[str, List[float]] = {}
        for iid, inv in self.inventory_states.items():
            scheduled_receipts_by_period[iid] = [
                float(inv.scheduled_receipts.get(p, 0.0)) for p in periods
            ]

        new_planned_orders, capacity_result = self._run_mrp_with_capacity(
            gross_requirements=gross_requirements,
            periods=periods,
            inventory_status=inventory_status,
            scheduled_receipts=scheduled_receipts_by_period,
        )

        # Convert PlannedOrder objects to dicts for plan comparator
        new_plan_dicts = self._orders_to_plan_dicts(new_planned_orders)

        # Enforce time fences
        enforced_plan_dicts, change_records = self._plan_comparator.enforce_time_fences(
            new_plan=new_plan_dicts,
            previous_plan=self._previous_plan,
            current_period=t,
            allow_slushy_changes=self.allow_slushy_changes,
        )

        # ---- Step 8 (pre-release): Nervousness metrics -----------------
        nervousness_metrics = self._nervousness_analyzer.calculate_metrics(
            previous_plan=self._previous_plan,
            new_plan=enforced_plan_dicts,
            cycle=cycle_num,
            overlapping_periods=periods,
        )
        self._nervousness_history.append(nervousness_metrics)

        # ---- Step 6: Release orders for t+1 ----------------------------
        released_orders = self._release_orders_for_period(enforced_plan_dicts, t + 1)

        # Build PlannedOrderExport list
        export_orders = self._build_export_orders(enforced_plan_dicts, cycle_num)
        # Transition released orders to RELEASED status (match on order_id or item_id & release_period)
        released_order_ids = {
            o.get("order_id") for o in released_orders if isinstance(o, dict) and o.get("order_id")
        }
        export_orders = [
            _replace_status(o, OrderStatus.RELEASED)
            if (o.order_id in released_order_ids or o.release_period == t + 1)
            else o
            for o in export_orders
        ]
        self._order_history.extend(export_orders)

        # ---- Step 7: Export to DES ------------------------------------
        des_path = os.path.join(
            self.des_export_dir, f"cycle_{cycle_num:04d}_period_{t:04d}.json"
        )
        DESExporter.export_planned_orders(export_orders, fmt="json", filepath=des_path)

        # ---- Finalise audit -------------------------------------------
        num_exceptions = (
            len(capacity_result.capacity_exceptions) if capacity_result else 0
        )
        is_feasible = capacity_result.is_capacity_feasible if capacity_result else True

        audit = CycleAuditRecord(
            cycle=cycle_num,
            planning_period=t,
            timestamp=timestamp,
            forecast_status=forecast.status,
            num_planned_orders=len(enforced_plan_dicts),
            num_released_orders=len(released_orders),
            num_capacity_exceptions=num_exceptions,
            is_capacity_feasible=is_feasible,
            nervousness_index=round(nervousness_metrics.nervousness_index, 4),
            fill_rate=self._compute_fill_rate(execution_results),
            des_export_path=des_path,
            notes="; ".join(notes_parts),
        )
        self._audit_trail.append(audit)

        # Update previous plan for next cycle
        self._previous_plan = enforced_plan_dicts

        logger.info(
            f"[Cycle {cycle_num}] Done — {len(enforced_plan_dicts)} orders, "
            f"nervousness={nervousness_metrics.nervousness_index:.3f}, "
            f"feasible={is_feasible}"
        )
        return audit

    def run_simulation(
        self,
        num_periods: int,
        execution_results_by_period: Optional[Dict[int, List[ExecutionRecord]]] = None,
        demand_actuals_by_period: Optional[Dict[int, Dict[str, float]]] = None,
        start_period: int = 1,
    ) -> SimulationSummary:
        """Run a full multi-period closed-loop rolling-horizon simulation.

        Parameters
        ----------
        num_periods:
            Number of planning periods to simulate.
        execution_results_by_period:
            Dict[period → List[ExecutionRecord]].  Provide actual DES output
            keyed by the period in which results are observed.
        demand_actuals_by_period:
            Dict[period → Dict[item_id → consumed_qty]] of real demand.
        start_period:
            First period to plan (default 1).

        Returns
        -------
        :class:`SimulationSummary` with aggregated metrics and full audit trail.
        """
        execution_map = execution_results_by_period or {}
        demand_map = demand_actuals_by_period or {}

        for t in range(start_period, start_period + num_periods):
            self.run_planning_cycle(
                t=t,
                execution_results=execution_map.get(t),
                demand_actuals=demand_map.get(t),
            )

        return self.get_simulation_summary()

    def get_simulation_summary(self) -> SimulationSummary:
        """Compute and return aggregate metrics from all completed cycles.

        Returns
        -------
        :class:`SimulationSummary` populated from the audit trail.
        """
        if not self._audit_trail:
            return SimulationSummary(
                num_periods=0,
                total_planned_orders=0,
                total_released_orders=0,
                avg_nervousness_index=0.0,
                max_nervousness_index=0.0,
                avg_fill_rate=0.0,
                total_capacity_exceptions=0,
                service_level_pct=0.0,
                nervousness_trend=[],
            )

        n_records = [a.nervousness_index for a in self._audit_trail]
        fill_rates = [a.fill_rate for a in self._audit_trail if a.fill_rate is not None]
        service_level_pct = (
            sum(1 for fr in fill_rates if fr >= self.target_fill_rate) / len(fill_rates) * 100.0
            if fill_rates else 0.0
        )

        return SimulationSummary(
            num_periods=len(self._audit_trail),
            total_planned_orders=sum(a.num_planned_orders for a in self._audit_trail),
            total_released_orders=sum(a.num_released_orders for a in self._audit_trail),
            avg_nervousness_index=round(float(np.mean(n_records)), 4),
            max_nervousness_index=round(float(np.max(n_records)), 4),
            avg_fill_rate=round(float(np.mean(fill_rates)) if fill_rates else 0.0, 4),
            total_capacity_exceptions=sum(a.num_capacity_exceptions for a in self._audit_trail),
            service_level_pct=round(service_level_pct, 2),
            nervousness_trend=n_records,
            cycle_audit_records=[a.to_dict() for a in self._audit_trail],
        )

    def ingest_execution_feedback(
        self,
        execution_results: List[ExecutionRecord],
        update_inventory: bool = True,
    ) -> None:
        """Ingest DES execution results and optionally reconcile inventory.

        When ``update_inventory=True``, each completed execution record is used
        to close the loop:
        - ``actual_quantity`` is added to on-hand stock (simulating WIP receipt).
        - If a receipt is early (actual_period < planned_period), the inventory
          is credited immediately.

        Parameters
        ----------
        execution_results:
            List of :class:`ExecutionRecord` from the DES.
        update_inventory:
            Whether to update inventory_states from actuals (default True).
        """
        self._execution_history.extend(execution_results)
        if not update_inventory:
            return

        for rec in execution_results:
            if rec.item_id in self.inventory_states:
                inv = self.inventory_states[rec.item_id]
                if rec.status in (OrderStatus.COMPLETED, OrderStatus.PARTIAL):
                    inv.on_hand += rec.actual_quantity
                    # Remove any matching scheduled receipt (now physically on hand)
                    inv.scheduled_receipts.pop(rec.planned_period, None)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _run_mrp_with_capacity(
        self,
        gross_requirements: Dict[str, List[float]],
        periods: List[int],
        inventory_status: Dict[str, Dict[str, Any]],
        scheduled_receipts: Dict[str, Dict[int, float]],
    ) -> Tuple[List[Any], Optional[CapacityAwareMRPResult]]:
        """Run MRP explosion (+ optional capacity pipeline) and return raw orders.

        Returns
        -------
        (planned_orders_list, CapacityAwareMRPResult_or_None)
        """
        if self._capacity_pipeline is not None:
            try:
                cap_result: CapacityAwareMRPResult = self._capacity_pipeline.run_capacity_aware_mrp(
                    mps_gross_requirements=gross_requirements,
                    periods=periods,
                    inventory_status=inventory_status,
                    scheduled_receipts=scheduled_receipts,
                    auto_level=True,
                    allow_overtime=True,
                    timing_key="due_period",
                )
                # Convert final_planned_orders (list of dicts) to PlannedOrder-like objects
                return cap_result.final_planned_orders, cap_result
            except Exception as exc:
                logger.warning(
                    f"CapacityAwareMRPPipeline failed ({exc}), falling back to plain MRP."
                )

        # Fallback: plain BOM explosion without capacity
        all_orders: List[Any] = []
        try:
            netting_results, _ = self.explosion_engine.run_multi_level_mrp(
                mps_gross_requirements=gross_requirements,
                periods=periods,
                inventory_status=inventory_status,
                scheduled_receipts=scheduled_receipts,
            )
            for netting in netting_results.values():
                all_orders.extend(getattr(netting, "planned_orders", []))
        except Exception as exc:
            logger.warning(f"BOMExplosionEngine.run_multi_level_mrp failed: {exc}")

        return all_orders, None

    @staticmethod
    def _orders_to_plan_dicts(orders: List[Any]) -> List[Dict[str, Any]]:
        """Convert a mixed list of PlannedOrder / dict objects to plain dicts."""
        result: List[Dict[str, Any]] = []
        for o in orders:
            if isinstance(o, dict):
                result.append(o)
            else:
                # PlannedOrder dataclass
                result.append({
                    "item_id": getattr(o, "item_id", "UNKNOWN"),
                    "due_period": int(getattr(o, "due_period", 0)),
                    "release_period": int(getattr(o, "release_period", 0)),
                    "quantity": float(getattr(o, "quantity", 0.0)),
                    "status": getattr(o, "status", "planned"),
                    "lot_sizing_rule": getattr(o, "lot_sizing_rule", "LFL"),
                })
        return result

    @staticmethod
    def _release_orders_for_period(
        plan_dicts: List[Dict[str, Any]],
        release_period: int,
    ) -> List[Dict[str, Any]]:
        """Select orders whose release_period equals the target period."""
        return [o for o in plan_dicts if int(o.get("release_period", -1)) == release_period]

    @staticmethod
    def _build_export_orders(
        plan_dicts: List[Dict[str, Any]],
        cycle_num: int,
    ) -> List[PlannedOrderExport]:
        """Convert plan dicts to PlannedOrderExport objects for DES."""
        exports: List[PlannedOrderExport] = []
        for idx, o in enumerate(plan_dicts):
            item_id = o.get("item_id", "UNKNOWN")
            due_period = int(o.get("due_period", 0))
            # Deterministic order ID includes cycle so it is unique across runs
            order_id = o.get("order_id") or f"C{cycle_num:04d}-{item_id}-P{due_period:04d}-{idx:03d}"
            exports.append(PlannedOrderExport(
                order_id=str(order_id),
                item_id=item_id,
                release_period=int(o.get("release_period", due_period - 1)),
                due_period=due_period,
                quantity=float(o.get("quantity", 0.0)),
                status=o.get("status", OrderStatus.PLANNED),
                lot_sizing_rule=o.get("lot_sizing_rule", "LFL"),
                metadata={"cycle": cycle_num},
            ))
        return exports

    @staticmethod
    def _compute_fill_rate(
        execution_results: Optional[List[ExecutionRecord]],
    ) -> Optional[float]:
        """Compute aggregate fill rate from execution results (None if no data)."""
        if not execution_results:
            return None
        total_planned = sum(r.planned_quantity for r in execution_results)
        total_actual = sum(r.actual_quantity for r in execution_results)
        if total_planned <= 0:
            return 1.0
        return round(min(1.0, total_actual / total_planned), 4)


